import { readFileSync, existsSync, writeFileSync, mkdirSync } from "node:fs";
import { join } from "node:path";

export const DEFAULT_ROUTING_CARD = [
  "[anysearch plugin active]",
  "Tools available (ans_* prefix):",
  "- search_web: real-time multi-source web search",
  "- research_web: deep research (minute-level, multi-hop)",
  "- recall_memory: search the local research archive (FTS5; older results slowly lose weight)",
  "- query_knowledge: query the knowledge base through the domain's retrieval adapter (with fts, it reads the whole store)",
  "- ans_chat: agent loop with retrieval augmentation",
  "",
  "Trigger rules:",
  "- Fresh facts / current events -> search_web",
  "- Complex multi-step research -> research_web",
  "- Recall prior search results -> recall_memory",
  "- Domain-specific knowledge base -> query_knowledge",
  "- Complex multi-tool research -> ans_chat",
  "- Skip a repeat search when recall_memory results already answer the question; search again when they are incomplete, out of date, or you need the latest",
  "",
  "Fail-open: if anysearch server is down, tools degrade gracefully (no block).",
  "For detailed guidance: see SKILL.md (anysearch skill).",
].join("\n");

export const MDC_CONTENT = [
  "---",
  "description: anysearch plugin routing card",
  "alwaysApply: true",
  "---",
  "",
  DEFAULT_ROUTING_CARD,
  "",
  "---",
  "This file is auto-generated by anysearch hook.",
  "Do not edit manually. Changes will be overwritten on next hook run.",
  "---",
].join("\n");

// audit (ensureMdc×3): single implementation shared by session-start,
// cursor, and antigravity — the only difference was the rules root
// (".cursor" vs ".antigravity"). Fail-open by contract.
export function ensureMdc(cwd: string, rulesRoot: string): void {
  if (mdcOptOut(cwd)) return;
  const rulesDir = join(cwd, rulesRoot, "rules");
  const mdcPath = join(rulesDir, "anysearch.mdc");
  try {
    if (existsSync(mdcPath)) {
      const existing = readFileSync(mdcPath, "utf8");
      if (existing === MDC_CONTENT) return;
    }
    mkdirSync(rulesDir, { recursive: true });
    writeFileSync(mdcPath, MDC_CONTENT, "utf8");
  } catch {
    // Fail-open: .mdc write failure is non-fatal.
  }
}

// high-user override via .anysearch/routing-card.json (fail-open).
// Shared reader: undefined on missing file; parse error -> stderr warning
// (same semantics for every key read off this file).
function readRoutingCardOverride(cwd: string): Record<string, unknown> | undefined {
  const overridePath = join(cwd, ".anysearch", "routing-card.json");
  try {
    if (existsSync(overridePath)) {
      return JSON.parse(readFileSync(overridePath, "utf8"));
    }
  } catch (e) {
    // Fail-open: JSON parse error -> stderr warning + fallback to default.
    process.stderr.write("[anysearch] routing-card.json parse error: " + (e instanceof Error ? e.message : String(e)) + "\n");
  }
  return undefined;
}

export function loadRoutingCard(cwd: string): string {
  const parsed = readRoutingCardOverride(cwd);
  if (parsed && typeof parsed.routingCard === "string" && parsed.routingCard.length > 0) {
    return parsed.routingCard;
  }
  return DEFAULT_ROUTING_CARD;
}

// mdc opt-out: {"mdc": false} suppresses the .mdc rule-file write for every
// ensureMdc call site. Only an explicit false opts out; missing file, missing
// key, or bad JSON all fail open (write as before).
function mdcOptOut(cwd: string): boolean {
  const parsed = readRoutingCardOverride(cwd);
  return parsed?.mdc === false;
}
