// Refresh the IANA root-zone snapshot the URL gate matches against.
//
// Design: the list is committed rather than fetched at runtime — a hook process
// has to answer offline, and a network round trip inside it would turn every
// tool call into a timeout risk. Updating it is a PR, so the change is reviewable.
//
// Usage: node apps/plugin/scripts/gen-tlds.mjs [--check]
//   --check writes nothing and exits 1 when the committed snapshot is stale,
//   so it can run on a machine that has network without touching the tree.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const SOURCE = "https://data.iana.org/TLD/tlds-alpha-by-domain.txt";
const OUT = resolve(dirname(fileURLToPath(import.meta.url)), "..", "src", "hooks", "tlds.generated.ts");

let text;
try {
  const res = await fetch(SOURCE, { signal: AbortSignal.timeout(20_000) });
  if (!res.ok) {
    console.error("gen-tlds: " + SOURCE + " returned HTTP " + res.status);
    process.exit(2);
  }
  text = await res.text();
} catch (e) {
  console.error("gen-tlds: could not fetch the IANA list — " + (e instanceof Error ? e.message : String(e)));
  process.exit(2);
}

const lines = text.split("\n").map((line) => line.trim()).filter(Boolean);
const header = lines[0] ?? "";
const version = /^#\s*Version\s+(\S+?),\s*Last Updated\s+(.+)$/i.exec(header);
if (!version) {
  console.error("gen-tlds: cannot read the version header: " + header);
  process.exit(2);
}
// Punycode entries arrive as "XN--…"; the gate compares lowercased labels.
const tlds = lines.slice(1).map((line) => line.toLowerCase()).sort();
if (tlds.length < 1000) {
  console.error("gen-tlds: only " + tlds.length + " entries — refusing to write a truncated list");
  process.exit(2);
}

const body = [
  "// Generated by apps/plugin/scripts/gen-tlds.mjs — do not edit by hand.",
  "// Source: " + SOURCE,
  "// Version: " + version[1] + " (last updated " + version[2] + ")",
  "//",
  "// A bare domain is only read as a host when its last label is in here; that",
  "// is what keeps `main.py`, `v1.2` and `config.toml` out of the URL gate.",
  'export const TLD_SNAPSHOT_VERSION = "' + version[1] + '";',
  "export const TLD_SNAPSHOT: ReadonlySet<string> = new Set([",
  ...tlds.map((t) => '  "' + t + '",'),
  "]);",
  "",
].join("\n");

if (process.argv.includes("--check")) {
  const current = readFileSync(OUT, "utf8");
  if (current !== body) {
    console.error("gen-tlds: snapshot is stale — run node apps/plugin/scripts/gen-tlds.mjs");
    process.exit(1);
  }
  console.log("gen-tlds: snapshot is current (" + tlds.length + " TLDs, version " + version[1] + ")");
  process.exit(0);
}

writeFileSync(OUT, body, "utf8");
console.log("gen-tlds: wrote " + tlds.length + " TLDs (version " + version[1] + ") to " + OUT);
