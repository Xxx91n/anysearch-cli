#!/usr/bin/env node
// ADR-0059 D6 (T-5): README ADR index generator (terraform-docs pattern).
//
// docs/adr/ is the single source of truth; the README index is a derived artifact. The generator
// owns the text between the BEGIN/END markers, so the index can never silently lag again (the
// round-57 failure mode: README claimed 0001-0046 while 59 ADRs existed on disk).
//
//   node scripts/gen-adr-index.mjs           # print the generated block
//   node scripts/gen-adr-index.mjs --write   # rewrite README between the markers
//   node scripts/gen-adr-index.mjs --check   # exit 1 if README is stale (ship-gate uses this)
//
// Node stdlib only (ADR-0020 D5).
import fs from "node:fs";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const ADR_DIR = path.join(ROOT, "docs", "adr");
const README = path.join(ROOT, "README.md");
export const BEGIN = "<!-- BEGIN ADR-INDEX (generated by scripts/gen-adr-index.mjs — do not edit by hand) -->";
export const END = "<!-- END ADR-INDEX -->";

export function adrEntries(dir = ADR_DIR) {
  const files = fs.readdirSync(dir).filter((f) => f.endsWith(".md")).sort();
  return files.map((file) => {
    const num = (file.match(/^(\d{3,4})/) ?? [])[1] ?? "????";
    const text = fs.readFileSync(path.join(dir, file), "utf8");
    const heading = text.split("\n").find((l) => l.trim().startsWith("# "));
    const m = heading ? heading.match(/^#\s*ADR-\d{3,4}\s*:?\s*(.*)$/) : null;
    const title =
      m && m[1] && m[1].trim()
        ? m[1].trim()
        : file.replace(/^\d{3,4}-/, "").replace(/\.md$/, "").replace(/-/g, " ");
    return { num, title, file };
  });
}

export function renderBlock(entries) {
  const first = entries[0] ? entries[0].num : "0000";
  const last = entries[entries.length - 1] ? entries[entries.length - 1].num : "0000";
  const lines = [
    BEGIN,
    "The complete numbered record lives in `docs/adr/` — ADR-" + first + " through ADR-" + last + ", all Accepted, consecutive.",
    "",
    "| ADR | Title |",
    "|-----|-------|",
  ];
  for (const e of entries) lines.push("| [" + e.num + "](docs/adr/" + e.file + ") | " + e.title.replace(/\|/g, "\\|") + " |");
  lines.push(END);
  return lines.join("\n");
}

export function replaceBlock(readme, block) {
  const i = readme.indexOf(BEGIN);
  const j = readme.indexOf(END);
  if (i < 0 || j < 0 || j < i) throw new Error("README is missing the ADR-INDEX markers");
  return readme.slice(0, i) + block + readme.slice(j + END.length);
}

function main() {
  const entries = adrEntries();
  const block = renderBlock(entries);
  const readme = fs.readFileSync(README, "utf8");
  const want = replaceBlock(readme, block);
  if (process.argv.includes("--write")) {
    if (want === readme) {
      console.log("gen-adr-index: README already up to date (" + entries.length + " ADRs)");
      return;
    }
    fs.writeFileSync(README, want, "utf8");
    console.log("gen-adr-index: README updated (" + entries.length + " ADRs)");
    return;
  }
  if (process.argv.includes("--check")) {
    if (want !== readme) {
      process.stderr.write("gen-adr-index: README ADR index is stale (" + entries.length + " ADRs on disk) — run: node scripts/gen-adr-index.mjs --write\n");
      process.exit(1);
    }
    console.log("gen-adr-index: README ADR index up to date (" + entries.length + " ADRs)");
    return;
  }
  process.stdout.write(block + "\n");
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
