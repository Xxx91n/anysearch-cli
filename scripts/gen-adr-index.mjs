#!/usr/bin/env node
// ADR-0059 D6 (T-5) + round-58 audit R-1: ADR index generator (terraform-docs pattern).
// R69 T1 (D-004/D-007): the derived artifact moved from README.md to docs/adr/index.md —
// the README keeps only a pointer; the generate-and-diff discipline is unchanged.
//
// docs/adr/ is the single source of truth; the README index is a derived artifact. R-1 fix: the
// source is the GIT TREE of a ref (default HEAD), never the working-tree filesystem. The previous
// version counted whatever files were on disk, so in a shared GitButler workspace it indexed staged
// (other-window) and other-branch files and the committed index was stale on a clean checkout
// (round-58 audit 5.1: 59 in the dirty workspace vs 57 in the branch tree = CI red).
//
//   node scripts/gen-adr-index.mjs                 # print the generated block (HEAD)
//   node scripts/gen-adr-index.mjs --write         # rewrite docs/adr/index.md between the markers
//   node scripts/gen-adr-index.mjs --check         # exit 1 if docs/adr/index.md is stale
//   node scripts/gen-adr-index.mjs --tree <ref>    # read docs/adr from <ref> instead of HEAD
//
// Node stdlib only (ADR-0020 D5).
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const INDEX = path.join(ROOT, "docs", "adr", "index.md");
export const BEGIN = "<!-- BEGIN ADR-INDEX (generated by scripts/gen-adr-index.mjs — do not edit by hand) -->";
export const END = "<!-- END ADR-INDEX -->";

function git(args) {
  return execFileSync("git", args, { cwd: ROOT, encoding: "utf8" });
}

// The ADR set comes from the git tree of `ref`, so staged or other-branch files can never leak in.
export function adrEntries(ref = "HEAD") {
  const listed = git(["ls-tree", "-r", "--name-only", ref, "--", "docs/adr"])
    .split("\n")
    .filter(Boolean)
    .filter((f) => f.endsWith(".md") && path.basename(f) !== "index.md")
    .sort();
  return listed.map((p) => {
    const file = path.basename(p);
    const num = (file.match(/^(\d{3,4})/) ?? [])[1] ?? "????";
    const text = git(["show", ref + ":" + p]);
    const heading = text.split("\n").find((l) => l.trim().startsWith("# "));
    const m = heading ? heading.match(/^#\s*ADR-\d{3,4}\s*:?\s*(.*)$/) : null;
    const title =
      m && m[1] && m[1].trim()
        ? m[1].trim()
        : file.replace(/^\d{3,4}-/, "").replace(/\.md$/, "").replace(/-/g, " ");
    return { num, title, file };
  });
}

export function renderBlock(entries) {
  const first = entries[0] ? entries[0].num : "0000";
  const last = entries[entries.length - 1] ? entries[entries.length - 1].num : "0000";
  const lines = [
    BEGIN,
    "The complete numbered record lives in `docs/adr/` — ADR-" + first + " through ADR-" + last + ".",
    "",
    "| ADR | Title |",
    "|-----|-------|",
  ];
  for (const e of entries) lines.push("| [" + e.num + "](" + e.file + ") | " + e.title.replace(/\|/g, "\\|") + " |");
  lines.push(END);
  return lines.join("\n");
}

export function replaceBlock(readme, block) {
  const i = readme.indexOf(BEGIN);
  const j = readme.indexOf(END);
  if (i < 0 || j < 0 || j < i) throw new Error("docs/adr/index.md is missing the ADR-INDEX markers");
  return readme.slice(0, i) + block + readme.slice(j + END.length);
}

function main() {
  const treeIdx = process.argv.indexOf("--tree");
  const ref = treeIdx >= 0 ? process.argv[treeIdx + 1] : "HEAD";
  if (!ref) {
    process.stderr.write("gen-adr-index: --tree requires a ref\n");
    process.exit(2);
  }
  const entries = adrEntries(ref);
  const block = renderBlock(entries);
  const exists = fs.existsSync(INDEX);
  const index = exists ? fs.readFileSync(INDEX, "utf8") : "";
  const want = exists ? replaceBlock(index, block) : "# Architecture decisions\n\n" + block + "\n";
  if (process.argv.includes("--write")) {
    if (want === index) {
      console.log("gen-adr-index: docs/adr/index.md already up to date (" + entries.length + " ADRs at " + ref + ")");
      return;
    }
    fs.writeFileSync(INDEX, want, "utf8");
    console.log("gen-adr-index: docs/adr/index.md updated (" + entries.length + " ADRs at " + ref + ")");
    return;
  }
  if (process.argv.includes("--check")) {
    if (want !== index) {
      process.stderr.write("gen-adr-index: docs/adr/index.md is stale (" + entries.length + " ADRs at " + ref + ") — run: node scripts/gen-adr-index.mjs --write\n");
      process.exit(1);
    }
    console.log("gen-adr-index: docs/adr/index.md up to date (" + entries.length + " ADRs at " + ref + ")");
    return;
  }
  process.stdout.write(block + "\n");
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
