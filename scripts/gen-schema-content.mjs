// Regenerate packages/store/src/schema-content.ts from schema.sql.
//
// The store reads schema.sql from the filesystem in ESM/tsx mode and falls back
// to this inlined constant in bundled CJS mode, so the two must stay identical.
// The old comment on schema-content.ts said "copy the content by hand"; a
// hand-copy is exactly how they drift. Run: node scripts/gen-schema-content.mjs

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const schemaPath = join(root, "packages", "store", "src", "schema.sql");
const outPath = join(root, "packages", "store", "src", "schema-content.ts");

const sql = readFileSync(schemaPath, "utf8");
// JSON.stringify gives a valid TS string literal for ANY input, including the
// quotes, backslashes and newlines this schema carries.
const body = [
  "// Auto-generated by build: inlines schema.sql for CJS bundling compatibility.",
  "// In dev mode (ESM/tsx), schema.sql is read from filesystem.",
  "// In bundled CJS mode, this inlined string is used directly.",
  "// Source: packages/store/src/schema.sql",
  "// Regenerate with: node scripts/gen-schema-content.mjs (never by hand).",
  "",
  "export const SCHEMA_SQL = " + JSON.stringify(sql) + ";",
  "",
].join("\n");

writeFileSync(outPath, body, "utf8");
console.log("wrote " + outPath + " (" + sql.length + " chars of schema)");
